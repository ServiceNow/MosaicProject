#!/usr/bin/env python3
"""Generate the paper-ready Privacy HopQA harness timing figure.

The timing values are critical-path wall-clock summaries from 300 recent q30
training traces. Parallel search/read calls are collapsed to one stage span
rather than summed across workers.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import matplotlib.pyplot as plt


OUT_DIR = Path(__file__).resolve().parent
PLOTS_DIR = OUT_DIR / "plots"
TABLES_DIR = OUT_DIR / "tables"

STAGES = [
    ("plan_s", "Plan", "#0072B2"),
    ("retrieve_s", "Retrieve", "#E69F00"),
    ("select_docs_s", "Select docs", "#CC79A7"),
    ("read_docs_s", "Read docs", "#009E73"),
    ("resolve_s", "Resolve", "#D55E00"),
]

ROWS = [
    {
        "group": "All attempted web hops",
        "n_web_hops": 329,
        "mean_total_s": 227.8,
        "median_total_s": 81.1,
        "plan_s": 15.6,
        "retrieve_s": 24.4,
        "select_docs_s": 10.7,
        "read_docs_s": 102.5,
        "resolve_s": 74.6,
    },
    {
        "group": "Answered web hops",
        "n_web_hops": 262,
        "mean_total_s": 115.2,
        "median_total_s": 74.7,
        "plan_s": 9.8,
        "retrieve_s": 15.8,
        "select_docs_s": 9.0,
        "read_docs_s": 50.5,
        "resolve_s": 30.0,
    },
    {
        "group": "Unanswered web hops",
        "n_web_hops": 67,
        "mean_total_s": 668.1,
        "median_total_s": 666.1,
        "plan_s": 38.0,
        "retrieve_s": 58.2,
        "select_docs_s": 17.3,
        "read_docs_s": 305.9,
        "resolve_s": 248.8,
    },
]


def make_plot() -> None:
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "font.size": 9,
            "axes.titlesize": 12,
            "axes.labelsize": 10,
            "xtick.labelsize": 8,
            "ytick.labelsize": 9,
            "legend.fontsize": 8,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
        }
    )

    fig, ax = plt.subplots(figsize=(7.1, 3.25))
    y_positions = list(range(len(ROWS)))
    left = [0.0] * len(ROWS)
    for key, label, color in STAGES:
        values = [float(row[key]) for row in ROWS]
        ax.barh(y_positions, values, left=left, color=color, edgecolor="white", linewidth=0.8, label=label)
        for idx, value in enumerate(values):
            if value >= 25:
                ax.text(left[idx] + value / 2, idx, f"{value:.0f}s", ha="center", va="center", color="white", fontsize=8, fontweight="bold")
        left = [base + value for base, value in zip(left, values)]

    labels = [f"{row['group']}\n(n={row['n_web_hops']}, median={row['median_total_s']:.0f}s)" for row in ROWS]
    ax.set_yticks(y_positions)
    ax.set_yticklabels(labels)
    ax.invert_yaxis()
    ax.set_xlabel("Mean critical-path seconds per web hop")
    ax.set_title("Where Privacy HopQA web-hop time is spent")
    ax.grid(axis="x", color="#d8dfdc", linewidth=0.8)
    ax.set_axisbelow(True)
    ax.spines[["top", "right", "left"]].set_visible(False)
    ax.tick_params(axis="y", length=0)
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, -0.34), ncol=5, frameon=False)
    fig.text(
        0.01,
        0.01,
        "Stage durations collapse parallel search/read calls to one wall-clock span, avoiding double-counting worker time.",
        fontsize=7.5,
        color="#5d6964",
    )
    fig.tight_layout(rect=(0, 0.11, 1, 1))
    for suffix in ("svg", "pdf"):
        fig.savefig(PLOTS_DIR / f"harness_webhop_timing.{suffix}", bbox_inches="tight")
    plt.close(fig)


def write_tables() -> None:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = TABLES_DIR / "harness_webhop_timing.csv"
    fieldnames = list(ROWS[0].keys())
    with csv_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(ROWS)

    tex_path = TABLES_DIR / "harness_webhop_timing.tex"
    with tex_path.open("w") as f:
        f.write("% Auto-generated by generate_harness_timing_plot.py\n")
        f.write("\\begin{tabular}{lrrrrrrr}\n")
        f.write("\\toprule\n")
        f.write("Group & n & Mean & Median & Plan & Retrieve & Read docs & Resolve \\\\\n")
        f.write("\\midrule\n")
        for row in ROWS:
            f.write(
                f"{row['group']} & {row['n_web_hops']} & {row['mean_total_s']:.1f} & "
                f"{row['median_total_s']:.1f} & {row['plan_s']:.1f} & {row['retrieve_s']:.1f} & "
                f"{row['read_docs_s']:.1f} & {row['resolve_s']:.1f} \\\\\n"
            )
        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")

    summary = {
        "measurement": "critical_path_wall_clock_seconds",
        "source_sample": "300 recent q30 training traces",
        "parallel_stage_definition": "max(end_s) - min(start_s) within each parallel search/read stage",
        "rows": ROWS,
    }
    (OUT_DIR / "harness_webhop_timing_summary.json").write_text(json.dumps(summary, indent=2))


def main() -> None:
    make_plot()
    write_tables()
    print(json.dumps({"rows": len(ROWS), "output_dir": str(OUT_DIR)}, indent=2))


if __name__ == "__main__":
    main()
